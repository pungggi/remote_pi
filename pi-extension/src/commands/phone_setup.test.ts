describe("runPhoneSetup — migrating the interim files (plan/173 review)", () => {
  const INTERIM = [
    "#!/data/data/com.termux/files/usr/bin/sh",
    "# written by hand on 2026-11-26",
    "termux-wake-lock",
    "nohup pi-supervisord >> ~/.pi/piper/boot.log 2>&1 &",
    "",
  ].join("\n");
  const QUESTION = "Replace the existing boot script? A dated copy is kept next to it (start-piper.sh.bak-<timestamp>).";

  test("a script that is not ours: diff shown and asked (default yes); no → nothing is changed", async () => {
    const h = harness();
    h.state.existingBootScript = INTERIM;
    h.state.answers[QUESTION] = false;
    expect(await runPhoneSetup(BASE_OPTS, h.deps)).toBe(1);
    expect(h.calls).toContain("confirm(Y):Replace");
    expect(h.calls.some((c) => c.startsWith("install"))).toBe(false);
    expect(h.calls).not.toContain("wakeLock");
    expect(h.lines.some((l) => l.includes("    - # written by hand on 2026-11-26"))).toBe(true);
    expect(h.lines.some((l) => l.includes("    + # start-piper.sh"))).toBe(true);
    expect(h.lines.some((l) => l.includes("    - nohup pi-supervisord >> ~/.pi/piper/boot.log 2>&1 &"))).toBe(true);
    expect(strip(h.lines).at(-1)).toMatch(/^boot script: kept /);
  });

  test("…yes → installed, and the dated copy install made is reported", async () => {
    const h = harness();
    h.state.existingBootScript = INTERIM;
    h.deps.install = (opts) => {
      h.calls.push(opts.force ? "install:force" : "install:plain");
      return { ok: true, unitPath: SCRIPT, log: [], backup: `${SCRIPT}.bak-20261126-143000`, diff: ["    - # written by hand on 2026-11-26"] };
    };
    expect(await runPhoneSetup(BASE_OPTS, h.deps)).toBe(0);
    expect(h.calls).toContain("confirm(Y):Replace");
    expect(h.calls).toContain("install:force");   // force only because the user agreed
    expect(strip(h.lines)).toContain(`boot script: ${SCRIPT} written; the previous version is kept at ${SCRIPT}.bak-20261126-143000`);
    expect(h.lines.some((l) => l.includes("The existing script is kept as start-piper.sh.bak-<timestamp>."))).toBe(true);
  });

  test("the question defaults to yes (Enter replaces, with the dated copy)", async () => {
    const h = harness();
    h.state.existingBootScript = INTERIM;
    expect(await runPhoneSetup(BASE_OPTS, h.deps)).toBe(0);
    expect(h.calls).toContain("confirm(Y):Replace");
  });

  test("our own older script: diff shown, no question", async () => {
    const h = harness();
    h.state.existingBootScript = "#!/data/data/com.termux/files/usr/bin/sh\n# older version. Generated by `remote-pi install`\n";
    expect(await runPhoneSetup(BASE_OPTS, h.deps)).toBe(0);
    expect(h.calls).toContain("install:plain");   // ours: no force needed
    expect(h.calls.some((c) => c.includes(":Replace"))).toBe(false);
    expect(h.lines.some((l) => l.includes("    + # start-piper.sh"))).toBe(true);
  });

  test("an identical script: no diff, no question", async () => {
    const h = harness();
    h.state.existingBootScript = h.deps.renderedBootScript();
    expect(await runPhoneSetup(BASE_OPTS, h.deps)).toBe(0);
    expect(h.lines.some((l) => l.includes("An existing boot script differs"))).toBe(false);
    expect(h.calls.some((c) => c.includes(":Replace"))).toBe(false);
  });

  test("the interim guard: announced before the run, 'retired' once the guard took over", async () => {
    const h = harness();
    h.state.interimGuard = true;
    h.deps.runBootScript = (p) => {
      h.calls.push(`run:${p}`);
      // `remote-pi guard run` (started by the script) stops and renames it.
      h.state.interimGuard = false;
      h.state.lastSeen = h.state.now;
      return true;
    };
    expect(await runPhoneSetup(BASE_OPTS, h.deps)).toBe(0);
    expect(h.lines.some((l) => l.includes("The interim guard (~/.pi/piper/piper-guard.sh) is retired by `remote-pi guard run`"))).toBe(true);
    expect(strip(h.lines)).toContain("interim guard: retired: remote-pi guard is the only guard now (its log lines are in ~/.pi/piper/guard.log)");
  });

  test("an interim guard still in place afterwards is a warning", async () => {
    const h = harness();
    h.state.interimGuard = true;
    h.deps.runBootScript = (p) => { h.calls.push(`run:${p}`); h.state.lastSeen = h.state.now; return true; };
    expect(await runPhoneSetup(BASE_OPTS, h.deps)).toBe(0);
    expect(strip(h.lines)).toContain("interim guard: still in place — see ~/.pi/piper/guard.log (`remote-pi guard run` stops and renames it on start)");
  });
});

